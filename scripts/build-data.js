#!/usr/bin/env node
/* 從試算表匯出的 tidy CSV（data/source）產生 js/data.js 與 data/*.csv
   Source: Google Sheet「115-1-資料清理_解答版」→ data/source/*.csv
   Run: node scripts/build-data.js */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const read = (f) => {
  const [head, ...rows] = parseCSV(fs.readFileSync(path.join(root, "data/source", f), "utf8"));
  return rows.filter((r) => r.length > 1).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
};
function parseCSV(text) {
  const out = []; let row = [], cell = "", q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) { if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; } else if (c === '"') q = false; else cell += c; }
    else if (c === '"') q = true;
    else if (c === ",") { row.push(cell); cell = ""; }
    else if (c === "\n") { row.push(cell); out.push(row); row = []; cell = ""; }
    else if (c !== "\r") cell += c;
  }
  if (cell || row.length) { row.push(cell); out.push(row); }
  return out;
}
const n = Number;

/* 1 · population & households 1990–2024 (表2-1) */
const yearly = read("yearly.csv");
const base = yearly[0];
const trend = yearly.map((d) => ({
  year: n(d.year), pop: n(d.pop_total), hh: n(d.households),
  popIdx: +(n(d.pop_total) / n(base.pop_total) * 100).toFixed(2),
  hhIdx: +(n(d.households) / n(base.households) * 100).toFixed(2)
}));

/* 2 · villages 2024 (表2-1 村別) */
const EN = { 上福村: "Shangfu", 大福村: "Dafu", 中福村: "Jhongfu", 天福村: "Tianfu", 本福村: "Benfu", 杉福村: "Shanfu", 南福村: "Nanfu", 漁福村: "Yufu" };
const villages = read("villages.csv").map((d) => ({
  zh: d.village, en: EN[d.village], pop: n(d.pop_total), hh: n(d.households), size: n(d.persons_per_hh)
}));

/* 3 · age structure 2014–2024 by sex (表2-3) */
const ages = read("age_long.csv");
const groups = [...new Set(ages.map((d) => d.age_group))];
const label = (g) => g.replace("歲以上", "+").replace("歲", "").replace("~", "–");
const years = [...new Set(ages.map((d) => n(d.year)))];
const get = (y, s, g) => n(ages.find((d) => n(d.year) === y && d.sex === s && d.age_group === g).population);
const pyramid = {
  ages: groups.map(label),
  years,
  men: Object.fromEntries(years.map((y) => [y, groups.map((g) => get(y, "male", g))])),
  women: Object.fromEntries(years.map((y) => [y, groups.map((g) => get(y, "female", g))]))
};
// dependency ratio = (0–14 + 65+) ÷ 15–64 × 100
const dependency = Object.fromEntries(years.map((y) => {
  const tot = groups.map((g) => get(y, "total", g));
  const kids = tot.slice(0, 3).reduce((a, b) => a + b), old = tot.slice(13).reduce((a, b) => a + b);
  const work = tot.slice(3, 13).reduce((a, b) => a + b);
  return [y, +((kids + old) / work * 100).toFixed(1)];
}));

/* 4–5 · final (settled) expenditure by function, NT$ million (表6-3) */
const fin = read("finance_long.csv").filter((d) => d.flow.startsWith("expenditure") && d.stage.startsWith("settled") && d.is_total === "N");
const GROUP = {
  econ: ["農業支出", "工業支出", "交通支出", "其他經濟服務支出"],
  admin: ["立法支出", "行政支出", "民政支出", "財務支出"],
  community: ["社區發展支出", "環境保護支出"],
  edu: ["教育支出", "文化支出"],
  welfare: ["社會救助支出", "福利服務支出", "國民就業支出", "醫療保健支出", "社會保險支出"],
  pension: ["退休撫卹支出", "債務付息支出", "還本付息事務支出", "第二預備金", "其他支出"]
};
const spend = (y, key) => +(fin.filter((d) => n(d.fiscal_year) === y && GROUP[key].includes(d.category))
  .reduce((a, d) => a + n(d.amount_k_ntd), 0) / 1000).toFixed(1);
const welfare = years.map((y) => ({ year: y, dep: dependency[y], welfare: spend(y, "welfare") }));
const budget = Object.keys(GROUP).map((key) => ({ key, v23: spend(2023, key), v24: spend(2024, key) }));

const DATA = { trend, villages, pyramid, welfare, budget };
fs.writeFileSync(path.join(root, "js/data.js"),
  "/* 自動產生 — generated by scripts/build-data.js from data/source/*.csv (Google Sheet 115-1-資料清理_解答版). Do not edit by hand. */\n" +
  "window.DATA = " + JSON.stringify(DATA) + ";\n");

/* tidy downloads for readers */
const csv = (f, head, rows) => fs.writeFileSync(path.join(root, "data", f), [head.join(","), ...rows.map((r) => r.join(","))].join("\n") + "\n");
csv("trend.csv", ["year", "population", "households", "population_index", "household_index"], trend.map((d) => [d.year, d.pop, d.hh, d.popIdx.toFixed(1), d.hhIdx.toFixed(1)]));
csv("villages.csv", ["village_zh", "village_en", "population", "households", "persons_per_household"], villages.map((d) => [d.zh, d.en, d.pop, d.hh, d.size]));
csv("pyramid.csv", ["year", "age_group", "men", "women"], years.flatMap((y) => pyramid.ages.map((a, i) => [y, a, pyramid.men[y][i], pyramid.women[y][i]])));
csv("welfare.csv", ["year", "dependency_ratio", "social_welfare_ntd_million"], welfare.map((d) => [d.year, d.dep, d.welfare]));
csv("budget.csv", ["category", "fy2023_ntd_million", "fy2024_ntd_million"], budget.map((d) => [d.key, d.v23, d.v24]));
console.log("js/data.js written:", { trend: trend.length, villages: villages.length, years, welfare, budget });
